/// Uses the installed just_audio implementation and its real method/event
/// channels. The payload is generated by the same C++ builder as the plugin;
/// tool/check_windows_audio_contract.ps1 checks that the fixture matches it.
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('cold first play survives late Windows preparation/settings data',
      () async {
    final platform = _WindowsProtocol();
    platform.install();
    final engine = JustAudioEngine();
    try {
      await engine.setFilePath(File('test-first-play.wav').absolute.path);
      expect(platform.playCalls, 0);
      final playing = engine.play();
      await platform.configurationEntered.future;
      // A native state packet from preparation is delivered while the first
      // play awaits audio-session activation. This used to cancel that play.
      await platform.sendSettings();
      await pumpEventQueue(times: 20);
      platform.releaseConfiguration.complete();
      await pumpEventQueue(times: 20);
      expect(platform.playCalls, 1,
          reason:
              'A single Play must reach the native engine after preparation');
      await playing;

      await engine.pause();
      await platform.sendSettings();
      await pumpEventQueue(times: 20);
      expect(platform.pauseCalls, 1);
      expect(platform.playCalls, 1);
      await engine.play();
      expect(platform.playCalls, 2);
      await engine.stop();
    } finally {
      if (!platform.releaseConfiguration.isCompleted) {
        platform.releaseConfiguration.complete();
      }
      await engine.dispose();
      platform.uninstall();
    }
  });
  test('typed file address reaches installed just_audio as a file URI',
      () async {
    final platform = _WindowsProtocol()..install();
    final engine = JustAudioEngine(isAndroid: false);
    final path = '${Directory.systemTemp.path}/Музыка/100% #.mp3';
    try {
      await engine.setSource(FileAudioSource(path));
      expect(platform.sourceUris, [Uri.file(path).toString()]);
      expect(platform.sourceTypes, ['progressive']);
    } finally {
      if (!platform.releaseConfiguration.isCompleted) {
        platform.releaseConfiguration.complete();
      }
      await engine.dispose();
      platform.uninstall();
    }
  });

  test(
      'Android content address reaches installed just_audio without file conversion',
      () async {
    final platform = _WindowsProtocol()..install();
    // Android routing is injected; no Android decoder or grants are simulated.
    final engine = JustAudioEngine(isAndroid: true);
    const value =
        'content://provider/document/primary%3AMusic%2FSong%25%23.m3u8?version=2';
    try {
      await engine.setSource(ContentUriAudioSource(value));
      expect(platform.sourceUris, [value]);
      expect(platform.sourceTypes, ['progressive']);
    } finally {
      if (!platform.releaseConfiguration.isCompleted) {
        platform.releaseConfiguration.complete();
      }
      await engine.dispose();
      platform.uninstall();
    }
  });

  test('non-Android engine rejects content before any native load', () async {
    final platform = _WindowsProtocol()..install();
    final engine = JustAudioEngine(isAndroid: false);
    try {
      await expectLater(
          engine.setSource(
              ContentUriAudioSource('content://provider/document/1')),
          throwsUnsupportedError);
      expect(platform.sourceUris, isEmpty);
    } finally {
      if (!platform.releaseConfiguration.isCompleted) {
        platform.releaseConfiguration.complete();
      }
      await engine.dispose();
      platform.uninstall();
    }
  });

  for (final mode in [
    _LoadMode.errorAfterOpening,
    _LoadMode.errorBeforeOpening,
    _LoadMode.methodError
  ]) {
    const preload = true;
    test('Windows $mode preload=$preload preserves HRESULT and permits retry',
        () async {
      final platform = _WindowsProtocol()..mode = mode;
      platform.install();
      final engine =
          JustAudioEngine(isWindows: true, handleInterruptions: false);
      try {
        await expectLater(
            engine.setSource(FileAudioSource(File('bad.m4a').absolute.path),
                preload: preload),
            throwsA(isA<just_audio.PlayerException>()
                .having((e) => e.code, 'HRESULT', -1072875836)));
        expect(platform.playCalls, 0);
        platform.mode = _LoadMode.ready;
        await engine.setFilePath(File('good.mp3').absolute.path);
        await engine.play();
        expect(platform.playCalls, 1);
      } finally {
        platform.releaseConfiguration.complete();
        await engine.dispose();
        platform.uninstall();
      }
    }, timeout: const Timeout(Duration(seconds: 10)));
  }

  test(
      'Windows silent native load times out, drains and retries on a new decoder',
      () async {
    final platform = _WindowsProtocol()..mode = _LoadMode.noEvents;
    platform.install();
    final engine = JustAudioEngine(
        isWindows: true,
        handleInterruptions: false,
        windowsLoadTimeout: const Duration(milliseconds: 150));
    try {
      await expectLater(engine.setFilePath(File('stalled.m4a').absolute.path),
          throwsA(isA<TimeoutException>()));
      expect(platform.playCalls, 0);
      expect(platform.disposals, greaterThan(0));
      platform.mode = _LoadMode.ready;
      await engine.setFilePath(File('next.flac').absolute.path);
      await engine.play();
      expect(platform.playCalls, 1);
    } finally {
      platform.releaseConfiguration.complete();
      await engine.dispose();
      platform.uninstall();
    }
  }, timeout: const Timeout(Duration(seconds: 10)));

  test('lazy source selection does not force native decoding', () async {
    final platform = _WindowsProtocol()..mode = _LoadMode.errorAfterOpening;
    platform.install();
    final engine = JustAudioEngine(isWindows: true, handleInterruptions: false);
    try {
      expect(
          await engine.setSource(
              FileAudioSource(File('lazy.m4a').absolute.path),
              preload: false),
          isNull);
      expect(platform.sourceUris, isEmpty);
      expect(platform.playCalls, 0);
    } finally {
      platform.releaseConfiguration.complete();
      await engine.dispose();
      platform.uninstall();
    }
  });
  test('stop interrupts loading without poisoning the next decoder', () async {
    final platform = _WindowsProtocol()..mode = _LoadMode.noEvents;
    platform.install();
    final engine = JustAudioEngine(isWindows: true, handleInterruptions: false);
    Object? failure;
    final loading = engine
        .setFilePath(File('pending.mp3').absolute.path)
        .then<void>((_) {}, onError: (Object e, StackTrace _) {
      failure = e;
    });
    try {
      await pumpEventQueue(times: 20);
      await engine.stop();
      await loading;
      expect(failure, isA<just_audio.PlayerInterruptedException>());
      platform.mode = _LoadMode.ready;
      await engine.setFilePath(File('next.mp3').absolute.path);
      await engine.play();
      expect(platform.playCalls, 1);
    } finally {
      platform.releaseConfiguration.complete();
      await engine.dispose();
      platform.uninstall();
    }
  }, timeout: const Timeout(Duration(seconds: 10)));
  test('service supersedes a stalled native load and plays the next source',
      () async {
    final platform = _WindowsProtocol()..mode = _LoadMode.noEvents;
    platform.install();
    final engine = JustAudioEngine(isWindows: true, handleInterruptions: false);
    final database = AppDatabase(NativeDatabase.memory());
    final player = JustAudioPlayerService(
        audioEngine: engine,
        playbackEvents: DriftRepositories(database).playbackEvents,
        isWindows: true,
        fileExists: (_) => true);
    final oldTrack = Track(
        filePath: 'C:/music/old.mp3',
        addedAt: DateTime(2026),
        updatedAt: DateTime(2026));
    final nextTrack = Track(
        filePath: 'C:/music/next.mp3',
        addedAt: DateTime(2026),
        updatedAt: DateTime(2026));
    final old = player.playTrack(oldTrack);
    try {
      await pumpEventQueue(times: 20);
      platform.mode = _LoadMode.ready;
      final next = player.playTrack(nextTrack);
      await platform.sendFailure();
      await Future.wait([old, next]);
      await pumpEventQueue(times: 20);
      expect(player.currentTrack, nextTrack);
      expect(player.state.hasError, isFalse);
      expect(platform.playCalls, 1);
    } finally {
      platform.releaseConfiguration.complete();
      await player.dispose();
      await database.close();
      platform.uninstall();
    }
  }, timeout: const Timeout(Duration(seconds: 10)));

  test('lost old method response is bounded and cannot damage a later decoder',
      () async {
    final response = Completer<Map<String, Object?>>();
    final platform = _WindowsProtocol()..loadResponse = response.future;
    platform.install();
    final engine = JustAudioEngine(
        isWindows: true,
        handleInterruptions: false,
        windowsLoadTimeout: const Duration(milliseconds: 40));
    try {
      await expectLater(engine.setFilePath(File('lost.m4a').absolute.path),
          throwsA(isA<TimeoutException>()));
      expect(platform.disposals, greaterThan(0));
      platform.loadResponse = null;
      await engine.setFilePath(File('next.mp3').absolute.path);
      response.complete({});
      await pumpEventQueue(times: 20);
      await engine.play();
      expect(platform.playCalls, 1);
    } finally {
      if (!response.isCompleted) response.complete({});
      platform.releaseConfiguration.complete();
      await engine.dispose();
      platform.uninstall();
    }
  }, timeout: const Timeout(Duration(seconds: 10)));

  test('native playback error after load reaches the real errorStream once',
      () async {
    final platform = _WindowsProtocol()..install();
    final engine = JustAudioEngine(isWindows: true, handleInterruptions: false);
    final errors = <Object>[];
    final sub = engine.errorStream.listen(errors.add);
    try {
      await engine.setFilePath(File('runtime.m4a').absolute.path);
      await engine.play();
      await platform.sendFailure();
      await pumpEventQueue(times: 30);
      expect(errors, hasLength(1));
      expect((errors.single as just_audio.PlayerException).code, -1072875836);
    } finally {
      await sub.cancel();
      platform.releaseConfiguration.complete();
      await engine.dispose();
      platform.uninstall();
    }
  });
}

enum _LoadMode {
  ready,
  errorAfterOpening,
  errorBeforeOpening,
  methodError,
  noEvents
}

class _WindowsProtocol {
  static const _main = MethodChannel('com.ryanheise.just_audio.methods');
  static const _session = MethodChannel('com.ryanheise.audio_session');
  static const _codec = StandardMethodCodec();
  final _messenger =
      TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;
  final configurationEntered = Completer<void>();
  final releaseConfiguration = Completer<void>();
  final List<String> _ids = [];
  String? _activeId;
  int playCalls = 0;
  int pauseCalls = 0;
  int disposals = 0;
  Future<Map<String, Object?>>? loadResponse;
  _LoadMode mode = _LoadMode.ready;
  final sourceUris = <String>[];
  final sourceTypes = <String>[];

  void _collectSources(Object? value) {
    if (value is Map) {
      if (value['uri'] is String) {
        sourceUris.add(value['uri'] as String);
        sourceTypes.add(value['type'] as String);
      }
      for (final child in value.values) {
        _collectSources(child);
      }
    } else if (value is List) {
      for (final child in value) {
        _collectSources(child);
      }
    }
  }

  void install() {
    _messenger.setMockMethodCallHandler(_session, (call) async {
      if (call.method == 'setConfiguration') {
        if (!configurationEntered.isCompleted) configurationEntered.complete();
        await releaseConfiguration.future;
      }
      return null;
    });
    _messenger.setMockMethodCallHandler(_main, (call) async {
      if (call.method == 'disposePlayer') disposals++;
      if (call.method == 'init') {
        final id = (call.arguments as Map)['id'] as String;
        _ids.add(id);
        _activeId = id;
        for (final kind in ['events', 'data']) {
          _messenger.setMockMethodCallHandler(
              MethodChannel('com.ryanheise.just_audio.$kind.$id'),
              (_) async => null);
        }
        _messenger.setMockMethodCallHandler(
            MethodChannel('com.ryanheise.just_audio.methods.$id'),
            (method) async {
          if (method.method == 'load') {
            _collectSources((method.arguments as Map)['audioSource']);
            if (loadResponse != null) return await loadResponse!;
            if (mode == _LoadMode.methodError) {
              throw PlatformException(
                  code: '-1072875836', message: 'Windows media source failed');
            }
            if (mode != _LoadMode.ready) {
              if (mode == _LoadMode.errorAfterOpening) {
                await _event(id, 'events', {
                  'processingState': 1,
                  'updateTime': DateTime.now().millisecondsSinceEpoch,
                  'updatePosition': 0,
                  'bufferedPosition': 0,
                  'duration': null,
                  'currentIndex': 0,
                });
              }
              if (mode != _LoadMode.noEvents) await sendFailure();
              return <String, Object?>{};
            }
            await _event(id, 'events', {
              'processingState': 3,
              'updateTime': DateTime.now().millisecondsSinceEpoch,
              'updatePosition': 0,
              'bufferedPosition': 0,
              'duration': 60000000,
              'currentIndex': 0,
            });
            return {'duration': 60000000};
          }
          if (method.method == 'play') playCalls++;
          if (method.method == 'pause') pauseCalls++;
          return <String, Object?>{};
        });
      }
      return <String, Object?>{};
    });
  }

  Future<void> sendSettings() async {
    final payload = jsonDecode(
        await File('test/fixtures/windows_player_settings_event.json')
            .readAsString());
    await _event(_activeId!, 'data', payload);
  }

  Future<void> sendFailure() async {
    final payload = jsonDecode(
        await File('test/fixtures/windows_player_error_event.json')
            .readAsString());
    await _event(_activeId!, 'events', payload);
  }

  Future<void> _event(String id, String kind, Object payload) async {
    final complete = Completer<void>();
    _messenger.handlePlatformMessage('com.ryanheise.just_audio.$kind.$id',
        _codec.encodeSuccessEnvelope(payload), (_) => complete.complete());
    await complete.future;
  }

  void uninstall() {
    _messenger.setMockMethodCallHandler(_main, null);
    _messenger.setMockMethodCallHandler(_session, null);
    for (final id in _ids) {
      for (final kind in ['methods', 'events', 'data']) {
        _messenger.setMockMethodCallHandler(
            MethodChannel('com.ryanheise.just_audio.$kind.$id'), null);
      }
    }
  }
}
